package Q6_DataTypeDemonstration;

public class DataTypeDemonstration {
    public static void main(String[] args) {
        int age = 25;
        float temperature = 36.6f;
        double distance = 12345.678;
        char letter = 'A';
        boolean isJavaFun = true;
        System.out.println("int age = " + age);
        System.out.println("float temperature = " + temperature);
        System.out.println("double distance = " + distance);
        System.out.println("char letter = " + letter);
        System.out.println("boolean isJavaFun = " + isJavaFun);
    }
}
